import { Body, Controller, Get, Headers, HttpCode, Post, Query } from '@nestjs/common';
import {
  clockInRequest,
  clockOutRequest,
  attendanceQuery,
  myTimeEntriesQuery,
  type ClockInRequest,
  type ClockOutRequest,
  type ClockResult,
  type Attendance,
  type AttendanceQuery,
  type MyTimeEntries,
  type MyTimeEntriesQuery,
} from '@shiftora/shared';

import { AppException } from '../../common/app-exception.js';
import { ZodValidationPipe } from '../../common/zod-validation.pipe.js';
import { errorCodes } from '@shiftora/shared';
import { Roles } from '../tenancy/decorators.js';
import { AttendanceService } from './attendance.service.js';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Clocking in and out, for every member — a phone in someone's hand is the normal caller.
 * A login with no staff profile is refused by the service (403 `attendance.not_linked`), which
 * is more useful than hiding the routes from roles that might legitimately have a profile.
 */
@Controller()
export class AttendanceController {
  constructor(private readonly attendance: AttendanceService) {}

  /**
   * `Idempotency-Key` is the device's own id for this punch. Sending the same key twice returns
   * the row the first call created (`created: false`) instead of a duplicate or a 409.
   */
  @Post('clock-in')
  @HttpCode(201)
  async clockIn(
    @Body(new ZodValidationPipe(clockInRequest)) body: ClockInRequest,
    @Headers('idempotency-key') idempotencyKey?: string,
  ): Promise<ClockResult> {
    return this.attendance.clockIn(body, parseKey(idempotencyKey));
  }

  @Post('clock-out')
  @HttpCode(200)
  clockOut(
    @Body(new ZodValidationPipe(clockOutRequest)) body: ClockOutRequest,
  ): Promise<ClockResult> {
    return this.attendance.clockOut(body);
  }

  /** The caller's own punches in a local-date range: what the clock screen and week view read. */
  /** A manager's view of one location: who punched, against which shift, and the totals. */
  @Get('attendance')
  @Roles('owner', 'manager')
  list(@Query(new ZodValidationPipe(attendanceQuery)) query: AttendanceQuery): Promise<Attendance> {
    return this.attendance.listForLocation(query);
  }

  @Get('me/time-entries')
  mine(
    @Query(new ZodValidationPipe(myTimeEntriesQuery)) query: MyTimeEntriesQuery,
  ): Promise<MyTimeEntries> {
    return this.attendance.listMine(query);
  }
}

/** An `Idempotency-Key` we can store: a UUID. Anything else is a client bug, refused loudly. */
function parseKey(value: string | undefined): string | undefined {
  if (value === undefined || value === '') return undefined;
  if (!UUID.test(value)) {
    throw new AppException(
      400,
      errorCodes.validationFailed,
      'Idempotency-Key must be a UUID generated by the client for this punch.',
    );
  }
  return value;
}
